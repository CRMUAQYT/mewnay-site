const LANG_LABELS = { ru: "RU", kk: "KK", en: "EN" };
const LANG_ORDER = ["ru", "kk", "en"];
const STORAGE_KEY = "mewnay-lang";

function detectLang() {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (saved && I18N[saved]) return saved;
  const browser = (navigator.language || "ru").slice(0, 2).toLowerCase();
  if (browser === "kk") return "kk";
  if (browser === "en") return "en";
  return "ru";
}

function applyLang(lang) {
  if (!I18N[lang]) lang = "ru";
  const dict = I18N[lang];
  document.documentElement.setAttribute("lang", dict.htmlLang);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const val = dict[key];
    if (typeof val === "string") el.innerHTML = val;
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    const spec = el.getAttribute("data-i18n-attr");
    spec.split(",").forEach((pair) => {
      const [attr, key] = pair.split(":").map((s) => s.trim());
      const val = dict[key];
      if (typeof val === "string") el.setAttribute(attr, val);
    });
  });

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("is-active", btn.dataset.lang === lang);
  });

  localStorage.setItem(STORAGE_KEY, lang);
}

function buildLangSwitcher() {
  const mount = document.getElementById("lang-switcher");
  if (!mount) return;
  mount.innerHTML = LANG_ORDER.map(
    (l) => `<button type="button" class="lang-btn" data-lang="${l}">${LANG_LABELS[l]}</button>`
  ).join("");
  mount.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => applyLang(btn.dataset.lang));
  });
}

document.addEventListener("DOMContentLoaded", () => {
  buildLangSwitcher();
  applyLang(detectLang());
});
